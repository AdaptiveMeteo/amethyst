class ossFM(object):
    """Use HITRAN precomputed tables to compute oss forward model (ir)"""

    def __init__(self, solar, hitran, imolid=None, imolind=None):
        """
        The object is initialized with a solar object,
        irradiances and the hitran coefficients.
        Optional arguments are the selection numbers of the species.
        """
        self.oss = oss_ir
        uimolid = hitran.get('molid')
        
        uimolid = uimolid[uimolid!=0]
        
        if imolid is None:
            imolid = array([1,2,3]) # Default Scene Molecular IDs
        self.nmol = len(imolid)

        # Set array with molecular ID from scene and LUT file           
        self.oss.set_imols(imolid,uimolid)

        self.cwvn  = hitran.get('cWvn')
        self.nfs   = hitran.nf()
        self.nchan = hitran.nchan()
        
        self.oss.set_hitran(hitran.get('pref'),
                            hitran.get('tmptab'),
                            hitran.get('tmpself'),
                            hitran.get('kself'),
                            hitran.get('vwvn'), 
                            hitran.get('isels'),
                            hitran.get('nnodes'), 
                            hitran.get('coef'),
                            hitran.get('ichmap'),
                            hitran.get('nchlist'), 
                            hitran.get('nch'),
                            hitran.get('channels'),
                            hitran.get('chanfreq'))
        vwvn = hitran.get('vwvn')
        self.oss.set_solar_irradiance(vwvn, solar.get(vwvn))
            
        self.oss.set_hitran_absorption_coefficients(hitran.get('kfix'),
                                                    hitran.get('kh2o'), 
                                                    hitran.get('dkh2o'),
                                                    hitran.get('kvar'),
                                                    hitran.get('imols_'),
                                                    hitran.get('nmols_'),
                                                    hitran.get('fmtLUT'),
                                                    hitran.get('xid'),
                                                    hitran.get('fixDMR'),
                                                    hitran.get('wvptab'),
                                                    hitran.get('dflt'),
                                                    hitran.get('molProf')
                                                    )   


    def compute(self, indata, outdata, dbg=False):
        """Compute measured radiances from the atmospheric status."""
        if 'xg' in indata.keys():
            xg = indata['xg']
            initempg = indata['initempg']
            initsking = indata['initsking']
            inipsfcg = indata['inipsfcg']
            nlev = initsking
            if 'constant_co2' in indata.keys():
                xg[2*nlev+2:2*nlev+2+nlev] = (zeros(nlev, dtype=float32) +
                                              indata['constant_co2'])
        elif 'temp' in indata.keys():
            nlev = len(indata['temp'])
            xg = zeros(nlev*(self.nmol+1)+2, dtype=float)
            xg[0:nlev] = indata['temp']
            xg[nlev] = indata['tskin']
            xg[nlev+1] = indata['psf']
            xg[nlev+2:nlev+2+nlev] = indata['h2o']
            if 'co2' in indata.keys():
                xg[2*nlev+2:2*nlev+2+nlev] = indata['co2']
            else:   
                if 'constant_co2' in indata.keys():
                    xg[2*nlev+2:2*nlev+2+nlev] = (zeros(nlev, dtype=float32) +
                                                  indata['constant_co2'])
                else:
                    print('Warning : Use default constant CO2 concentration')
                    xg[2*nlev+2:2*nlev+2+nlev] = (zeros(nlev, dtype=float32) +
                                                  5.9407297521829605E-004)

            xg[3*nlev+2:3*nlev+2+nlev] = indata['o3']
            # Fortran indexes below !
            initempg = 1
            initsking = nlev+1
            inipsfcg = initsking+1
        else:
            raise KeyError('Neither xg or temperature data in input')
            
        sfgrd     = indata['sfgrd']
        emref     = indata['emrf']
        obsangle  = indata['obsang']
        solzenith = indata['solzenith']
        azangle   = indata['azangle']
        obslevel  = indata['obslevel']
        lat       = indata['lat']

        if 'y' not in outdata.keys():
            nparg = len(xg)
            outdata['y'] = zeros(self.nchan, float32)
            outdata['xkt'] = zeros((nparg, self.nchan), float32, order='F')
            outdata['xkemrf'] = zeros((sfgrd.size, self.nchan,2),
                                       float32, order='F')
            outdata['paxkemrf'] = zeros((2, self.nchan),
                                       float32, order='F')
        self.oss.ossdrv_ir(xg, sfgrd,emref,obsangle,solzenith,azangle,obslevel, 
                           outdata['y'], outdata['xkt'],outdata['xkemrf'],outdata['paxkemrf'],lat,
                           zsurf = 0.0,
                           puser = indata['pressure'],
                           dbg=dbg)

